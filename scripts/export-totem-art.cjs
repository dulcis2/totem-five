/**
 * Regenerates src/ui/totemArt.ts from the design page design/totem-faces.html.
 *
 * The design page is where the 25 totem faces were drawn and iterated on. This
 * script opens it in a headless browser, asks it for the final SVG of every face,
 * and writes them out as static strings so the game needs no drawing code.
 *
 * Usage (needs Playwright with Chromium available):
 *   node scripts/export-totem-art.cjs
 */
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');

(async () => {
  const page = path.resolve(__dirname, '../design/totem-faces.html');
  const out = path.resolve(__dirname, '../src/ui/totemArt.ts');
  const browser = await chromium.launch();
  const p = await browser.newPage();
  await p.goto('file://' + page);
  const faces = await p.evaluate(() =>
    Object.fromEntries(CARDS.map((c) => [c.t, FACES[c.t].map((f, v) => ({ name: f.name || f.n, svg: art(c, v) }))])),
  );
  await browser.close();

  const body = Object.entries(faces)
    .map(([t, list]) => `  ${t}: [\n${list.map((f) => `    { name: ${JSON.stringify(f.name)}, svg: ${JSON.stringify(f.svg)} },`).join('\n')}\n  ],`)
    .join('\n');
  const src = `/**
 * Totem face art: five faces per card type, drawn as SVG on a 100 x 140 card.
 *
 * GENERATED by scripts/export-totem-art.cjs from design/totem-faces.html. Do not
 * edit by hand; change the design page and re-run the script.
 *
 * Layout contract: the carved totem block fills the bottom 48 units (y 92-140) of
 * the card and the wings crown sits just above it. Table stacks raise each card by
 * exactly 48/140 of its height, so the blocks join into one pole and only the top
 * card shows its wings.
 */
import type { CardType } from '../engine/types';

export interface TotemFace {
  name: string;
  /** Inner SVG markup for a viewBox of 0 0 100 140. */
  svg: string;
}

export const TOTEM_FACES: Record<CardType, TotemFace[]> = {
${body}
};

/** Which face a card shows: card ids end in a copy number (e.g. "shatter-7"). */
export function faceIndex(cardId: string | undefined, count: number): number {
  const n = Number(cardId?.match(/(\\d+)$/)?.[1]);
  return Number.isFinite(n) && n > 0 ? (n - 1) % count : 0;
}
`;
  fs.writeFileSync(out, src);
  console.log('Wrote', out, Object.values(faces).map((l) => l.length));
})();
